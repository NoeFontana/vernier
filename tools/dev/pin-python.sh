#!/usr/bin/env bash
# Pin the interpreter pyo3's build script resolves to this checkout's venv,
# by writing a git-ignored .cargo/config.toml at the checkout root.
#
# Unpinned, pyo3 reads VIRTUAL_ENV and PATH, which differ between bare
# `cargo` and `uv run cargo`, so each switch re-ran its build script and
# rebuilt pyo3, numpy and vernier-ffi. The file is generated rather than
# committed: wheel builds (manylinux containers) and the venv-less CI
# jobs must keep resolving their own interpreter.
#
# Run by `just bootstrap`, after the venv exists.

set -euo pipefail

root=$(git rev-parse --show-toplevel)
python=$root/.venv/bin/python
[ -x "$python" ] || { echo "error: $python missing; run 'uv sync' first" >&2; exit 1; }

mkdir -p "$root/.cargo"
cat >"$root/.cargo/config.toml" <<EOF
# Generated by tools/dev/pin-python.sh; git-ignored, safe to delete.
[env]
PYO3_PYTHON = "$python"
EOF
